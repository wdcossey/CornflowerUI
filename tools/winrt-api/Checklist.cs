using System.Text;
using System.Xml.Linq;

namespace WinRtApi;

/// <summary>
/// One control's checklist, in Markdown, for the plan's first section (docs/PROCESS.md, "Plan"):
/// every row of the WinRT spec, from the <c>.winmd</c> and <c>generic.xaml</c>, beside Avalonia's
/// equivalent, with a box to tick and an Action to fill in.
/// </summary>
internal static class Checklist
{
    /// <summary>What a row says when Avalonia has nothing for it.</summary>
    internal const string None = "none";

    public static string Render(
        string fullName,
        IReadOnlyList<ApiType> api,
        DefaultStyle? style,
        ThemeResources? resources,
        IReadOnlySet<string> tokens,
        AvaloniaSide avalonia,
        string command)
    {
        var name = ApiReader.Short(fullName);
        var avaloniaName = avalonia.Type is { } type ? $"`{type.FullName}`" : "none: a new control (rung 5)";
        var avaloniaVersion = typeof(Avalonia.Controls.Control).Assembly.GetName().Version;
        var md = new StringBuilder();
        md.AppendLine($"# {name}: checklist");
        md.AppendLine();
        md.AppendLine($"> Generated by `{command}`, from the Windows Phone 8.1 SDK's `Windows.winmd`, `generic.xaml` and");
        md.AppendLine("> `themeresources.xaml`, read as a specification (ADR 0002), and Avalonia " +
            $"{avaloniaVersion!.ToString(3)}. Tick each row, or give a one-line reason it's left out, and fill in");
        md.AppendLine("> Action. The Avalonia column is mechanical: a member of the same name, a part Avalonia's control");
        md.AppendLine("> declares, a state by the draft mapping rules (docs/ARCHITECTURE.md). Check each.");
        md.AppendLine();
        md.AppendLine($"WinRT `{fullName}`; Avalonia {avaloniaName}.");
        md.AppendLine();

        foreach (var declared in api)
        {
            var on = declared.Name == name ? "" : $", from `{declared.Name}`";
            Section(md, $"Properties{on}", ["WinRT", "Type", "Avalonia", "Action"], declared.Properties.Select(p => new[]
            {
                Code(p.Name) + (p.Settable ? "" : " (read-only)") + (p.Dependency ? "" : " (not a dependency property)"),
                Code(p.Type),
                Avalonia(avalonia.Property(p.Name)),
                "",
            }));
            Section(md, $"Events{on}", ["WinRT", "Handler", "Avalonia", "Action"], declared.Events.Select(e => new[]
            {
                Code(e.Name),
                Code(e.Handler),
                Avalonia(avalonia.Event(e.Name)),
                "",
            }));
            Section(md, $"Methods{on}", ["WinRT", "Avalonia", "Action"], declared.Methods.Select(m => new[]
            {
                Code(m.Signature) + (m.Overridable ? " (protected, overridable)" : ""),
                Avalonia(avalonia.Method(m.Name)),
                "",
            }));
        }

        if (style is null)
        {
            md.AppendLine("## Default style");
            md.AppendLine();
            md.AppendLine($"_`generic.xaml` has no default style for `{name}`._");
            md.AppendLine();
            return md.ToString();
        }

        Section(md, "Default style: setters", ["Property", "Value", "Avalonia", "Action"], style.Setters.Select(s => new[]
        {
            Code(s.Property),
            Code(s.Value),
            Avalonia(avalonia.Property(s.Property)),
            "",
        }));

        var avaloniaParts = avalonia.Type is null ? "" : $" Avalonia's control looks for: {(avalonia.Parts.Count == 0 ? "none" : string.Join(", ", avalonia.Parts.Select(Code)))}.";
        Section(md, "Template parts", ["Part", "Element", "Avalonia", "Action"], style.Parts.Select(p => new[]
        {
            Code(p.Name),
            Code(p.Element),
            avalonia.Type is null ? Code("PART_" + p.Name) : Avalonia(avalonia.Part(p.Name)),
            "",
        }), avaloniaParts.Trim());

        Section(md, "Visual states", ["Group", "State", "What it changes", "Avalonia", "Action"], style.States.Select(s => new[]
        {
            Code(s.Group),
            Code(s.Name),
            s.Changes.Count == 0 ? "nothing" : string.Join("<br>", s.Changes.Select(c => Code(c.Description))),
            StateCell(avalonia, s.Name),
            "",
        }));

        Section(md, "Transitions", ["Group", "From → To", "Duration", "What it runs", "Action"], style.Transitions.Select(t => new[]
        {
            Code(t.Group),
            $"{Code(t.From)} → {Code(t.To)}",
            t.Duration.Length == 0 ? "" : Code(t.Duration),
            t.Changes.Count == 0 ? "nothing" : string.Join("<br>", t.Changes.Select(c => Code(c.Description))),
            "",
        }));

        Section(md, "Resources", ["Key", "Dark", "Light", "In Cornflower's Tokens", "Action"], style.Resources.Select(key =>
        {
            var (dark, light) = resources?[key] ?? (null, null);
            return new[]
            {
                Code(key),
                dark is null ? "not in themeresources.xaml" : Code(dark),
                light is null ? "" : light == dark ? "same" : Code(light),
                tokens.Contains(key) ? "yes" : "no",
                "",
            };
        }));

        return md.ToString();
    }

    private static string StateCell(AvaloniaSide avalonia, string state)
    {
        switch (avalonia.State(state))
        {
            case null:
                return "no rule";
            case "":
                return "the theme's plain setters";
            case { } selector:
                var missing = avalonia.NotRaised(selector);
                return Code("^" + selector) + (missing.Count == 0 ? "" : $" ({string.Join(", ", missing)} not raised by Avalonia's `{avalonia.Type!.Name}`)");
        }
    }

    private static void Section(StringBuilder md, string title, string[] headers, IEnumerable<string[]> rows, string note = "")
    {
        var list = rows.ToList();
        md.AppendLine($"## {title} ({list.Count})");
        md.AppendLine();
        if (note.Length > 0)
        {
            md.AppendLine(note);
            md.AppendLine();
        }

        if (list.Count == 0)
        {
            md.AppendLine("_none_");
            md.AppendLine();
            return;
        }

        md.AppendLine("| ✓ | " + string.Join(" | ", headers) + " |");
        md.AppendLine("|---|" + string.Concat(headers.Select(_ => "---|")));
        foreach (var row in list)
        {
            md.AppendLine("| [ ] | " + string.Join(" | ", row) + " |");
        }

        md.AppendLine();
    }

    private static string Avalonia(string? found) => found is null ? None : Code(found);

    /// <summary>Code in a table cell: one line, its pipes escaped, a backtick in it handled.</summary>
    internal static string Code(string text)
    {
        var line = string.Join(" ", text.Split((char[])['\r', '\n', '\t'], StringSplitOptions.RemoveEmptyEntries).Select(s => s.Trim())).Replace("|", "\\|");
        return line.Contains('`') ? $"`` {line} ``" : $"`{line}`";
    }

    /// <summary>Every <c>x:Key</c> in the theme's <c>Tokens/</c> files.</summary>
    public static IReadOnlySet<string> TokenKeys(string tokensFolder)
    {
        XNamespace x = "http://schemas.microsoft.com/winfx/2006/xaml";
        return Directory.EnumerateFiles(tokensFolder, "*.axaml", SearchOption.AllDirectories)
            .SelectMany(file => XDocument.Load(file).Descendants())
            .Select(e => (string?)e.Attribute(x + "Key"))
            .OfType<string>()
            .ToHashSet(StringComparer.Ordinal);
    }
}
