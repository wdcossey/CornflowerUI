// Writes the SHA-256 of every Microsoft file in the reference folder, one per line, for the repository
// guard test (tests/Cornflower.Tests/Repository/). Hashes and file names only: no content.
// Usage: node tools/guard/hash-reference.js <reference folder> > tests/Cornflower.Tests/Repository/microsoft-sha256.txt
//
// Everything under the folder is Microsoft's, or decompiled or converted from Microsoft's files, except
// our own output, listed in OURS: the reference app's runs (refapp/), our screenshots (vm-extras/captures/,
// screens-*/, grab-test-*/), the inventories collect-vm.ps1 writes, the xbf tool's manifests (index.json
// in an xbf-json/ or sdk-json/ folder), and the loose notes and logs at the top. So a folder pulled later,
// such as another emulator image, is hashed without a change here. Empty files are skipped: their hash
// would match any empty file.
//
// A text file (no NUL byte in its first 8,000 bytes, git's test) is hashed twice: as it is, and with a UTF-8
// BOM dropped and CRLF turned into LF, as git stores it under `* text=auto`. The guard hashes a repository
// file both ways too, so a copy matches whichever line endings the checkout gave it.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = process.argv[2];
if (!root) { console.error('usage: node hash-reference.js <reference folder>'); process.exit(1); }

const OURS = [
  /^[^/]+$/,                                   // loose files at the top: notes, logs
  /^refapp\//,
  /^vm-extras\/captures\//,
  /^screens-[^/]*\//,
  /^grab-test-[^/]*\//,
  /^inventory-[^/]*\/inventory\.(json|md)$/,
  /(^|\/)(xbf-json|sdk-json(\/[^/]+)?)\/index\.json$/,
];

const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p) : [p];
});

const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

// The text form git would store: no BOM, LF line endings. Null for a binary file.
function textForm(bytes) {
  if (bytes.subarray(0, 8000).includes(0)) return null;
  let s = bytes;
  if (s.length >= 3 && s[0] === 0xef && s[1] === 0xbb && s[2] === 0xbf) s = s.subarray(3);
  const out = [];
  for (let i = 0; i < s.length; i++) if (!(s[i] === 0x0d && s[i + 1] === 0x0a)) out.push(s[i]);
  return Buffer.from(out);
}

const byHash = new Map();
for (const file of walk(root)) {
  const rel = path.relative(root, file).split(path.sep).join('/');
  if (OURS.some(re => re.test(rel))) continue;
  const bytes = fs.readFileSync(file);
  if (bytes.length === 0) continue;
  const name = path.basename(file);
  const raw = sha(bytes);
  if (!byHash.has(raw)) byHash.set(raw, name);
  const text = textForm(bytes);
  if (text && text.length > 0) {
    const normal = sha(text);
    if (!byHash.has(normal)) byHash.set(normal, name);
  }
}

const lines = [...byHash].sort(([a], [b]) => a.localeCompare(b)).map(([h, name]) => `${h}  ${name}`);
process.stdout.write(`# SHA-256 of the Microsoft files in the reference folder (pulled from the VM or an emulator image, or decompiled or\n# converted from them), each as it is and, for text, as git stores it. Generated by tools/guard/hash-reference.js.\n# ${lines.length} distinct hashes. Hashes and names only.\n${lines.join('\n')}\n`);
